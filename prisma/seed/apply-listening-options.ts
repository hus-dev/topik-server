function levelFor(q: number): number {
  if (q <= 20) return 3;
  if (q <= 35) return 4;
  if (q <= 45) return 5;
  return 6;
}

function getDatabaseUrl() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('DATABASE_URL is not set');
  const url = new URL(connectionString);
  if (url.hostname === 'localhost' || url.hostname === '::1') {
    url.hostname = '127.0.0.1';
  }
  if (!url.searchParams.has('allowPublicKeyRetrieval')) {
    url.searchParams.set('allowPublicKeyRetrieval', 'true');
  }
  return url.toString();
}

const prisma = new PrismaClient({
  adapter: new PrismaMariaDb(getDatabaseUrl()),
});

async function main() {
  let updated = 0;

  for (const [qStr, opts] of Object.entries(OPTIONS)) {
    const q = Number(qStr);
    const level = levelFor(q);
    const setId = `listening-real-lvl${level}`;
    const questionId = `${setId}-${round}-q${q.toString().padStart(2, '0')}`;

    const question = await prisma.questions.findUnique({
      where: { id: questionId },
      include: { question_options: { orderBy: { option_number: 'asc' } } },
    });

    if (!question) {
      console.log(`⚠ question not found: ${questionId}`);
      continue;
    }

    for (let i = 0; i < 4; i += 1) {
      const option = question.question_options[i];
      if (option && option.content !== opts[i]) {
        await prisma.question_options.update({
          where: { id: option.id },
          data: { content: opts[i] },
        });
      }
    }
    updated += 1;
  }

  console.log(`✅ 83회 듣기 보기(선택지) ${updated}개 문항에 반영 완료 (1~3번 그림 문제 제외)`);
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });

